# A word pair is only counted inside one run of Cyrillic words. Any other
# token between two words (a digit, punctuation, Latin text, wiki markup, a
# line break) ends the run. The first Wikipedia attempt (2135d98) counted
# pairs over the text with everything but Cyrillic deleted, so "байна. 2010
# онд" became the pair байна → онд, and year phrases dominated predictions.
#
# A pair is also skipped when its second word is capitalized: Mongolian
# capitalizes proper names, and a name continuation is not a next-word
# prediction (Сайн ноён хан, the historical aimag, made ноён the top word
# after сайн).
TOKEN_RE = re.compile(r"[а-яёөүА-ЯЁӨҮ]+|[^\sа-яёөүА-ЯЁӨҮ]+|\n")
WORD_RE = re.compile(r"[а-яёөүА-ЯЁӨҮ]+")


def wiki_counts(cache_dir: str):
    """(unigram, bounded bigram) counts over the Wikipedia dump, cached."""
    uni_path = os.path.join(cache_dir, "wiki-clean-unigrams-v2.tsv")
    bi_path = os.path.join(cache_dir, "wiki-clean-bigrams-v2.tsv")
    if os.path.exists(uni_path) and os.path.exists(bi_path):
        print(f"  cached: {uni_path}, {bi_path}")
        uni = collections.Counter()
        with open(uni_path, encoding="utf-8") as f:
            for line in f:
                w, n = line.rstrip("\n").split("\t")
                uni[w] = int(n)
        bi = collections.Counter()
        with open(bi_path, encoding="utf-8") as f:
            for line in f:
                a, b, n = line.rstrip("\n").split("\t")
                bi[(a, b)] = int(n)
        return uni, bi

    dump = os.path.join(cache_dir, "mnwiki.xml.bz2")
    if not os.path.exists(dump):
        sys.exit(f"error: {dump} missing; see tools/build_wikipedia_corpus.py")
    print("  counting Wikipedia words and bounded word pairs (a few minutes)…")
    uni = collections.Counter()
    bi = collections.Counter()
    pages = 0
    for text in articles(dump):
        pages += 1
        prev = None
        for tok in TOKEN_RE.findall(clean(text)):
            if WORD_RE.fullmatch(tok):
                word = tok.lower()
                uni[word] += 1
                if prev is not None and not tok[0].isupper():
                    bi[(prev, word)] += 1
                prev = word
            else:
                prev = None
    print(f"  {pages} articles, {sum(uni.values())} words, {len(uni)} distinct")
    with open(uni_path, "w", encoding="utf-8") as f:
        for w, n in uni.most_common():
            f.write(f"{w}\t{n}\n")
    bi = collections.Counter({k: v for k, v in bi.items() if v >= 3})
    with open(bi_path, "w", encoding="utf-8") as f:
        for (a, b), n in bi.most_common():
            f.write(f"{a}\t{b}\t{n}\n")
    return uni, bi


def load_authority():
    rows = []
    with open(AUTHORITY_PATH, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or line.startswith("cyrillic\t"):
                continue
            cols = line.rstrip("\n").split("\t")
            if len(cols) >= 2:
                rows.append((cols[0], cols[1]))
    return rows


def load_removed():
    removed = set()
    with open(REMOVED_PATH, encoding="utf-8") as f:
        for line in f:
            cols = line.rstrip("\n").split("\t")
            if len(cols) == 4:
                removed.add((cols[0], cols[1]))
    return removed


def full_keys(cyr: str, latin: str = "") -> set:
    """Keys from a full romanization of the word: the ones typed_keys()
    produces before its lossy shortcuts (ы/ий typed as a single i, ь/ъ
    dropped)."""
    keys = {g.fold_key(latin)} if latin else set()
    for dedupe in (True, False):
        for ye in ("ye", "e"):
            latin_form = g.romanize(cyr, dedupe, ye)
            if latin_form and g.LATIN_RE.fullmatch(latin_form):
                keys.add(g.fold_key(latin_form))
    return keys


def frequency_for_key(key: str, cyr: str, freq: int, latin: str = "") -> int:
    """A word reached only through a lossy shortcut ranks below every word
    that matches the typed key in full: `bi` is би before бий (bii), whatever
    the corpus says. The legacy build left this to frequency, which worked
    because its news and lyrics use the pronoun often; an encyclopedia does
    not (Wikipedia: бий 8,069, би 2,268)."""
    return freq if key in full_keys(cyr, latin) else 0


def valid_traditional(trad: str) -> bool:
    return bool(trad) and all(ord(ch) in g.ALLOWED_TRADITIONAL for ch in trad)


def main(cache_dir: str):
    print("Licence-clean build (issue #20): no mongolian-nlp input")
    entries = g.load_dictionary(cache_dir)
    uni, bi = wiki_counts(cache_dir)
    removed = load_removed()

    # (key, traditional) -> [cyrillic, frequency]
    merged = {}
    dict_spelling = {}
    dropped_junk = dropped_shape = 0
    for e in entries:
        latin, cyr, trad = e["latin"], e["cyrillic"], e["traditional"]
        if not (g.LATIN_RE.fullmatch(latin) and g.CYRILLIC_RE.fullmatch(cyr)):
            dropped_shape += 1
            continue
        if not valid_traditional(trad):
            dropped_junk += 1
            continue
        trad = g.normalize_traditional(trad)
        dict_spelling[cyr] = trad
        freq = uni.get(cyr, 0)
        for key in g.typed_keys(cyr) | {g.fold_key(latin)}:
            key_freq = frequency_for_key(key, cyr, freq, latin)
            slot = merged.get((key, trad))
            if slot is None or key_freq > slot[1]:
                merged[(key, trad)] = [cyr, key_freq]

    # CC0 rows carry frequency 0, the policy 77b62cc set for this import:
    # mazaalai is single-source and unreviewed, so its rows rank below every
    # dictionary spelling of the same key. Where the MIT dictionary spells a
    # word differently, the dictionary's spelling stays the Space default: it
    # is the larger, Mongolia-sourced list, and the project's reference
    # standard is Mongolia's (issue #21). It is also name-heavy: 29.7% of its
    # rows that Wikipedia attests are disharmonic compound names
    # (алтанчимэг ᠠᠯᠲᠠᠨᠴᠢᠮᠡᠭ), against 1.3% of the dictionary's.
    added = alternates = skipped = 0
    for cyr, trad in load_authority():
        if not g.CYRILLIC_RE.fullmatch(cyr) or "-" in cyr or not valid_traditional(trad):
            skipped += 1
            continue
        trad = g.normalize_traditional(trad)
        known = cyr in dict_spelling
        if known and dict_spelling[cyr] == trad:
            continue
        for key in g.typed_keys(cyr):
            if (key, trad) not in merged:
                merged[(key, trad)] = [cyr, 0]
        if known:
            alternates += 1
        else:
            added += 1

    dropped_removed = 0
    for key, trad in removed:
        if merged.pop((key, trad), None) is not None:
            dropped_removed += 1

    # Within a key, commonest first: the order the legacy table uses and
    # Lexicon.exactMatches(forKey:) returns.
    rows = sorted(((key, trad, cyr, freq) for (key, trad), (cyr, freq) in merged.items()),
                  key=lambda r: (r[0], -r[3], r[1], r[2]))

    # Training rows for tools/learn_orthography.py: the MIT dictionary's own
    # spellings only. Adding the CC0 rows made the learned rules worse on
    # common words (tsag came out ᠴᠭ, bolno ᠪᠯᠣᠨ᠎ᠠ): mazaalai is name-heavy,
    # writes ᠢ where the dictionary writes ᠶᠢ, and has alignment errors.
    training_path = os.path.join(cache_dir, "clean-training.tsv")
    with open(training_path, "w", encoding="utf-8", newline="\n") as f:
        for key, trad, cyr, freq in rows:
            if dict_spelling.get(cyr) == trad:
                f.write(f"{key}\t{trad}\t{cyr}\t{freq}\n")
    with open(g.LEXICON_PATH, "w", encoding="utf-8", newline="\n") as f:
        for key, trad, cyr, freq in rows:
            f.write(f"{key}\t{trad}\t{cyr}\t{freq}\n")
    print(f"Wrote {len(rows)} lexicon rows ({len({r[2] for r in rows})} Cyrillic words)")
    print(f"  dictionary: dropped {dropped_junk} defective, {dropped_shape} malformed")
    print(f"  CC0: {added} new words, {alternates} alternate spellings, {skipped} skipped")
    print(f"  re-removed {dropped_removed} rows listed in {os.path.basename(REMOVED_PATH)}")

    # Next-word table: same thresholds as the legacy build.
    best = {}
    for (key, trad), (cyr, freq) in merged.items():
        # Prefer the dictionary spelling, then the commoner row.
        rank = (dict_spelling.get(cyr) == trad, freq)
        if cyr not in best or rank > best[cyr][0]:
            best[cyr] = (rank, trad)
    successors = collections.defaultdict(collections.Counter)
    for (a, b), n in bi.items():
        if a in best and b in best:
            successors[a][b] += n
    bigram_rows = []
    for a, counts in successors.items():
        if uni.get(a, 0) < g.MIN_HEAD_FREQ:
            continue
        for b, n in counts.most_common(g.TOP_SUCCESSORS):
            if n >= g.MIN_BIGRAM:
                bigram_rows.append((a, best[b][1], b, n))
    bigram_rows.sort(key=lambda r: (r[0], -r[3], r[2]))
    with open(g.BIGRAMS_PATH, "w", encoding="utf-8", newline="\n") as f:
        for a, trad, b, n in bigram_rows:
            f.write(f"{a}\t{trad}\t{b}\t{n}\n")
    print(f"Wrote {len(bigram_rows)} next-word rows for "
          f"{len({r[0] for r in bigram_rows})} head words")

    with open(SOURCES_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(SOURCES_TEXT)
    print(f"Wrote {SOURCES_PATH}")
