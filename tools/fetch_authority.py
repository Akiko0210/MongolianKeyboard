#!/usr/bin/env python3
"""
Build an authority dictionary of Cyrillic -> traditional-script spellings from
sources whose redistribution rights are explicit.

Why this exists: Cyrillic cannot be converted to traditional script by letter
rules. Cyrillic encodes 1940s Khalkha pronunciation; the script preserves
13th-century orthography, and the irregulars sit in the commonest words
(өдөр -> ᠡᠳᠦᠷ, аав -> ᠠᠪᠤ, ээж -> ᠡᠵᠢ). Measured on held-out text, the rule
path is ~27% correct. Coverage of a verified dictionary is what makes the
conversion deterministic, so this tool grows that dictionary.

Every source carries its licence in SOURCES below. A source without an
explicit grant does not get added, whatever its quality: docs/DATA_PROVENANCE.md
already carries unresolved rights questions and this tool exists partly to
replace that data, not to add more of it.

"Verified" is never taken from a source's own README. A row is reported as
corroborated only when two independent sources give the same spelling.

    python3 tools/fetch_authority.py --out docs/authority.tsv
"""

import argparse
import csv
import io
import os
import sys
import urllib.request
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CACHE = os.path.join(ROOT, ".lexicon-cache")
CYRILLIC = set("абвгдеёжзийклмноөпрстуүфхцчшщъыьэюя-")


def norm_mazaalai(blob):
    """suragch/mongolian-datasets mazaalai: cyrillic,menksoft,unicode,latin."""
    for row in csv.DictReader(io.StringIO(blob)):
        cyr, uni = (row.get("cyrillic") or "").strip().lower(), (row.get("unicode") or "").strip()
        if cyr and uni and all(c in CYRILLIC for c in cyr):
            yield cyr, uni


SOURCES = {
    "mazaalai": {
        "url": "https://raw.githubusercontent.com/suragch/mongolian-datasets/HEAD/mazaalai/dataset.csv",
        "licence": "CC0-1.0 (public domain dedication)",
        "repo": "https://github.com/suragch/mongolian-datasets",
        "note": "Cyrillic/Menksoft/Unicode/Latin table. Includes many proper nouns.",
        "parse": norm_mazaalai,
    },
}


def fetch(name, spec):
    path = os.path.join(CACHE, f"authority-{name}" + os.path.splitext(spec["url"])[1])
    if not os.path.exists(path):
        os.makedirs(CACHE, exist_ok=True)
        sys.stderr.write(f"downloading {name} <- {spec['url']}\n")
        urllib.request.urlretrieve(spec["url"], path)
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "authority.tsv"))
    ap.add_argument("--only", help="restrict to one source name")
    args = ap.parse_args()

    entries = defaultdict(dict)          # cyrillic -> {source: spelling}
    stats = Counter()
    for name, spec in SOURCES.items():
        if args.only and name != args.only:
            continue
        for cyr, uni in spec["parse"](fetch(name, spec)):
            entries[cyr][name] = uni
            stats[name] += 1

    corroborated = agreed = conflicted = 0
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("# Cyrillic -> traditional script. Generated by tools/fetch_authority.py.\n")
        for name, spec in SOURCES.items():
            if args.only and name != args.only:
                continue
            fh.write(f"# source {name}: {spec['licence']} — {spec['repo']}\n")
        fh.write("# columns: cyrillic\ttraditional\tsources\tstatus\n")
        for cyr, by_source in sorted(entries.items()):
            spellings = set(by_source.values())
            if len(by_source) > 1:
                corroborated += 1
                if len(spellings) == 1:
                    agreed += 1
                    status = "agreed"
                else:
                    conflicted += 1
                    status = "conflict"
            else:
                status = "single-source"
            best = Counter(by_source.values()).most_common(1)[0][0]
            fh.write(f"{cyr}\t{best}\t{','.join(sorted(by_source))}\t{status}\n")

    print(f"wrote {args.out}")
    for name, n in stats.items():
        print(f"  {name:<12} {n:>7} rows   {SOURCES[name]['licence']}")
    print(f"  {'TOTAL':<12} {len(entries):>7} distinct Cyrillic words")
    if corroborated:
        print(f"  corroborated by 2+ sources: {corroborated} "
              f"({agreed} agree, {conflicted} conflict)")
    else:
        print("  corroborated by 2+ sources: 0 — single source only, so these "
              "spellings are unconfirmed, not verified.")


if __name__ == "__main__":
    sys.exit(main())
